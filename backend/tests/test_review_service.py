    def test_record_accept_decision(self):
        """Verify accepting a finding records decision and transitions report to in_review."""
        payload = CreateReviewDecisionRequest(
            finding_id="find_01",
            decision=ReviewDecisionType.ACCEPTED,
            reviewer_name="Alice (Lead)",
            reviewer_comment="Verified architecture claim against code.",
        )
        record = record_review_decision(self.report_id, payload)

        self.assertEqual(record.item_id, "find_01")
        self.assertEqual(record.decision, ReviewDecisionType.ACCEPTED)
        self.assertEqual(record.reviewer_name, "Alice (Lead)")

        # Verify summary
        with get_db_context() as conn:
            cursor = conn.cursor()
            cursor.execute("SELECT status, report_json FROM handover_reports WHERE id = ?", (self.report_id,))
            rep_row = cursor.fetchone()
            self.assertEqual(rep_row["status"], "in_review")
            data = json.loads(rep_row["report_json"])
            f1 = next(f for f in data["raw_findings"] if f["id"] == "find_01")
            self.assertEqual(f1["review_decision"], "accepted")
            self.assertEqual(f1["reviewer_name"], "Alice (Lead)")

    def test_record_reject_decision(self):
        """Verify rejecting a finding records decision and preserves finding."""

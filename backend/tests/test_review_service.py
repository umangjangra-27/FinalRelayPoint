            # Must remain the original AI title, NOT "Edit 1 Title"
            self.assertEqual(orig_f1["title"], "Use SQLite for Persistence")

            active_f1 = next(f for f in data["raw_findings"] if f["id"] == "find_01")
            self.assertEqual(active_f1["title"], "Edit 2 Title")

